WITH ITGR AS (
SELECT
		DISTINCT
CTSTKY AS ITEMGROUP
		,
	TRIM( CAST (
        CTTX40 AS CHAR(40) CCSID 65535
    )) AS ITGR_Description
FROM
		MVXBDTA888.CSYTAB
WHERE
		CTCONO = 888
	AND CTSTCO = 'ITGR'
)
,
PRDGRP AS (
SELECT
		DISTINCT
CTSTKY AS ProductGROUP
		,
	TRIM( CAST (
        CTTX40 AS CHAR(40) CCSID 65535
    )) AS ITCL_Description
FROM
		MVXBDTA888.CSYTAB
WHERE
		CTCONO = 888
	AND CTSTCO = 'ITCL'
)
,
CSMGRP AS (
SELECT
		DISTINCT
CTSTKY AS CUSOTMERGROUP
		,
	TRIM( CAST (
        CTTX40 AS CHAR(40) CCSID 65535
    )) AS CSMGRP_Description
FROM
		MVXBDTA888.CSYTAB
WHERE
		CTCONO = 888
	AND CTSTCO = 'CUCL'
)
SELECT
	T01.UCCONO AS Company
	,
	T01.UCDIVI AS Division
	,
	T01.UCFACI AS Facility
	,
	T01.UCCUNO AS Customer#
	,
	T02.OKCUNM AS Customer_name
	,
	T02.OKCUCL AS Customer_group
	,
	T02.OKDIGC AS Discount_group
	,
	CSMGRP.CSMGRP_Description AS CSMGRP_TXT
	,
	T01.UCIVDT AS Invoice_date
	,
	T01.UCACDT AS Accounting_date
	,
	T01.UCIVNO AS Invoice#
	,
	T01.UCORNO AS CO#
	,
	T01.UCPONR AS Line#
	,
	T01.UCITNO AS Item#
	,
	T04.OBITDS AS NAME
	,
	T01.UCIVQT AS Invoiced_QTY
	,
	T01.UCUCOS AS Cost_price
	,
	T01.UCSAAM AS Line_amount
	,
	T01.UCCUCD AS Currency
	,
	T01.UCITGR AS Item_group
	,
	ITGR_Description AS Item_GRP_Text
	,
	T01.UCITCL AS Product_group
	,
	ITCL_Description
	,
	T05.MMCFI1 AS Where_use
	,
	T01.UCORTP AS CO_type
	,
	T01.UCDIA1 AS Discount_AMT_1
	,
	T01.UCDIA2 AS Discount_AMT_2
	,
	T01.UCOFRA AS Total_discount_AMT
	,
	T03.OACUOR AS ORDER#_CUSTOMER
	,
	T03.OAYREF AS Your_reference
	,
	T01.UCORDT AS Order_date
	,
	T02.OKOREF AS Our_reference
	,
	T04.OBRORN AS Reference_order#
	,
	T04.OBRORL AS Reference_order_line
	,
	T03.OAOREF AS Our_reference
	,
	T01.UCWCON AS Contact_method
	,
	T02.OKCFC9 AS UDF_customer
	,
	T01.UCFRE1 AS Statistics_customer
	,
	T03.OASMCD AS Salesperson
FROM
	MVXBDTA888.OSBSTD AS T01
LEFT JOIN MVXBDTA888.OCUSMA AS T02 ON
	T01.UCCONO = T02.OKCONO
	AND T01.UCCUNO = T02.OKCUNO
LEFT JOIN MVXBDTA888.OOHEAD AS T03 ON
	T01.UCORNO = T03.OAORNO
	AND T01.UCCONO = T03.OACONO
	AND T01.UCDIVI = T03.OADIVI
LEFT JOIN MVXBDTA888.OOLINE AS T04 ON
	T01.UCORNO = T04.OBORNO
	AND T01.UCPONR = T04.OBPONR
	AND T01.UCCONO = T04.OBCONO
LEFT JOIN MVXBDTA888.MITMAS AS T05 ON
	T01.UCITNO = T05.MMITNO
LEFT JOIN ITGR ON
	ITEMGROUP = T01.UCITGR
LEFT JOIN PRDGRP ON
	ProductGROUP = T01.UCITCL
LEFT JOIN CSMGRP ON
	CUSOTMERGROUP = T02.OKCUCL
WHERE
	/*CHANGE AS REQUEST*/
	NOT T01.UCDIVI IN (
		'100', '908', '909'
	)
	AND T01.UCCONO = '888'
	AND T01.UCCUCD='USD'
