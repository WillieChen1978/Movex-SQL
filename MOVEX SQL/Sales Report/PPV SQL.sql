SELECT distinct IFCONO,IFDIVI,IBFACI,IFSUNO,IFITST,IFIVDT,IFSINO,IFPUNO,IFPNLI,IFPNLS,IBITNO,IBSDQA,
IBPUPR,IFIVQA,IFIVPR,IFRGDT,IFVONO,IBOURR,IFIVDI,IFSCOP,MMITGR,MMITCL,
round(INVAMT/(case when IFSERA=0 then 1 else  IFSERA end),2) as INVAMT,
round(CSTAMT,2) as CSTAMT,
round(INVAMT/(case when IFSERA=0 then 1 else  IFSERA end),2)-round(CSTAMT,2) as PPV,
T2.MTITNO,(T1.IFIVQA*T2.EZACAM) as EZACAM

FROM 
(
 Select 
T01.IFCONO,T01.IFDIVI,T02.IBFACI,T01.IFSUNO,T01.IFITST,T01.IFIVDT,T01.IFSINO,T01.IFPUNO,T01.IFPNLI,T01.IFPNLS,
T02.IBITNO,T03.MMITGR,T03.MMITCL,T02.IBSDQA,T02.IBPUPR,T01.IFIVQA,T01.IFIVPR,T01.IFRGDT,T01.IFVONO,T02.IBOURR,
T01.IFIVDI,T01.IFSCOP,(T01.IFIVQA*T01.IFIVPR) as INVAMT,(T01.IFIVQA*T01.IFSCOP) as CSTAMT,
((T01.IFIVQA*T01.IFIVPR)-(T01.IFIVQA*T01.IFSCOP)) as PPV ,T01.IFSERA


FROM 
"E607D15C"."MVXBDTA888"."MPINVT" T01
INNER JOIN   
"E607D15C"."MVXBDTA888"."MPLINE" T02
ON 
T01.IFPUNO = T02.IBPUNO
AND T01.IFPNLI = T02.IBPNLI
AND T01.IFPNLS = T02.IBPNLS
INNER JOIN 
"E607D15C"."MVXBDTA888"."MITMAS" T03       
ON
T02.IBITNO = T03.MMITNO
WHERE 
T01.IFCONO = '888'
AND T01.IFRGDT BETWEEN ? AND ?
) T1

left join
(
select 
Ta.EZAIT7,Tb.EZITNO,Ta.EZITNO as MTITNO,sum(Ta.EZACAM/Tb.EZACQT)/count(*) as EZACAM
FROM 
(Select * from "E607D15C"."MVXBDTA888"."CINACC" 
where EZAIT1 in ('0110909','0110908') AND EZTFAM='1' and EZFSRC='C' AND EZANBR<>'999999999' AND EZACDT>='20070505') Ta
inner join 
(Select * from "E607D15C"."MVXBDTA888"."CINACC" 
where EZAIT1 in ('0120001','0138000') AND EZTFAM='1' and EZFSRC<>'C' AND EZANBR<>'999999999' AND EZACDT>='20070505') Tb
on Ta.EZANBR=Tb.EZANBR
where trim(Ta.EZAIT7)<>'' 
group by Ta.EZAIT7,Tb.EZITNO,Ta.EZITNO
having sum(Ta.EZACAM)<>0 
) T2
on T1.IFPUNO=T2.EZAIT7 and T1.IBITNO=T2.EZITNO

order by IFCONO,IFDIVI,IBFACI,IFSUNO